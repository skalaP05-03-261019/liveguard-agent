"""전송 방식과 Graph 로직을 분리하기 위한 최소 인터페이스 초안."""

from typing import Any, Protocol


class ReadTools(Protocol):
    async def call(self, name: str, arguments: dict[str, Any]) -> dict[str, Any]: ...


class BackendClient(Protocol):
    async def get_task_context(self, task_id: str) -> dict[str, Any]: ...
    async def request_plan(self, case_id: str, payload: dict[str, Any]) -> dict[str, Any]: ...
    async def save_result(self, task_id: str, payload: dict[str, Any]) -> None: ...
    async def emit_event(self, task_id: str, payload: dict[str, Any]) -> None: ...


class ActionTools(Protocol):
    async def execute(self, command: dict[str, Any]) -> dict[str, Any]: ...
    async def get_status(self, action_id: str) -> dict[str, Any]: ...
